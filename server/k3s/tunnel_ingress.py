#!/usr/bin/env python3
"""Render a credentials-free overlay for Cloudflare TLS → existing Traefik HTTP → Nakama."""
import argparse
import copy
from pathlib import Path
import re
import yaml
from standalone import resources

HOST = 'zorxapi.daiyooo.com'


def overlay(host=HOST, traefik_namespace='kube-system', traefik_name='traefik'):
    if not re.fullmatch(r'[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?', host) or '.' not in host:
        raise ValueError('host must be a DNS hostname, without a scheme/path')
    for value in (traefik_namespace,traefik_name):
        if not re.fullmatch(r'[a-z0-9][a-z0-9.-]*',value): raise ValueError('invalid namespace/pod-label value')
    policy = copy.deepcopy(next(doc for doc in resources() if doc['kind']=='NetworkPolicy' and doc['metadata']['name']=='nakama-api-only'))
    policy['spec']['ingress'][0]['from'].append({
        'namespaceSelector': {'matchLabels': {'kubernetes.io/metadata.name': traefik_namespace}},
        'podSelector': {'matchLabels': {'app.kubernetes.io/name': traefik_name}}})
    ingress = {'apiVersion':'networking.k8s.io/v1','kind':'Ingress',
        'metadata': {'name':'nakama-public','namespace':'zorx-staging',
            'annotations': {'traefik.ingress.kubernetes.io/router.entrypoints':'web', 'traefik.ingress.kubernetes.io/router.middlewares':'zorx-staging-origin-budget@kubernetescrd,zorx-staging-origin-buffer@kubernetescrd'}},
        'spec': {'ingressClassName':'traefik','rules':[{'host':host,'http':{'paths':[
            {'path':'/','pathType':'Prefix','backend':{'service':{'name':'nakama','port':{'number':7350}}}}]}}]}}
    return [policy,ingress]


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--host',default=HOST)
    parser.add_argument('--traefik-namespace',default='kube-system')
    parser.add_argument('--traefik-name',default='traefik')
    parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args()
    args.output.parent.mkdir(parents=True,exist_ok=True)
    with args.output.open('x') as stream:
        stream.write('# Generated by server/k3s/tunnel_ingress.py. No Secrets; overlay for existing staging backend.\n')
        stream.write('# Edge TLS is handled by Cloudflare Tunnel; Traefik origin listens on HTTP web:80.\n')
        yaml.safe_dump_all(overlay(args.host,args.traefik_namespace,args.traefik_name),stream,sort_keys=False)
    print('Created',args.output)


if __name__=='__main__':main()
