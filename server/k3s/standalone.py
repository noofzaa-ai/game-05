#!/usr/bin/env python3
"""Build a portable apply-only YAML on the dev machine; the server needs only kubectl."""
import argparse
import os
from pathlib import Path
import yaml
from render import render
from prepare_secrets import generate

STORAGE_PATH = '/data/k3s/volumes/zorx-game/postgres-staging'
NODE_PORT = 30350


def resources():
    documents = render('staging')['items']
    for item in documents:
        if item['kind'] == 'StatefulSet' and item['metadata']['name'] == 'postgres':
            spec = item['spec']
            spec.pop('volumeClaimTemplates')
            pod = spec['template']['spec']
            pod['volumes'].append({'name': 'data', 'hostPath': {'path': STORAGE_PATH, 'type': 'DirectoryOrCreate'}})
            # hostPath does not inherit fsGroup ownership; prepare only this dedicated directory.
            # No recursive chown, no deletion, and no chmod of the shared parent directory.
            pod['initContainers'] = [{
                'name': 'prepare-data-directory', 'image': pod['containers'][0]['image'],
                'command': ['sh', '-ec', 'mkdir -p /var/lib/postgresql/data/pgdata; chown 70:70 /var/lib/postgresql/data /var/lib/postgresql/data/pgdata; chmod 700 /var/lib/postgresql/data/pgdata'],
                'securityContext': {'runAsUser': 0, 'runAsGroup': 0, 'runAsNonRoot': False,
                    'allowPrivilegeEscalation': False, 'readOnlyRootFilesystem': True,
                    'capabilities': {'drop': ['ALL'], 'add': ['CHOWN', 'FOWNER', 'DAC_OVERRIDE']}},
                'volumeMounts': [{'name': 'data', 'mountPath': '/var/lib/postgresql/data'}],
                'resources': {'requests': {'cpu': '10m', 'memory': '16Mi'}, 'limits': {'cpu': '100m', 'memory': '64Mi'}}}]
        elif item['kind'] == 'Service' and item['metadata']['name'] == 'nakama':
            item['spec']['type'] = 'ClusterIP'
            item['spec'].pop('externalTrafficPolicy', None)
            item['spec']['ports'][0].pop('nodePort', None)
        elif item['kind'] == 'NetworkPolicy' and item['metadata']['name'] == 'nakama-api-only':
            item['spec']['ingress'][0]['from'] = [
                {'ipBlock': {'cidr': '100.64.0.0/10'}},  # Tailscale clients; Local preserves source IP
                {'podSelector': {}}]  # same namespace (future backend components)
    return documents


def bundle():
    docs = resources()
    return docs[:1] + generate('staging') + docs[1:]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--resources-only', action='store_true', help='Versionable YAML; contains Secret references but no credentials')
    args = parser.parse_args()
    docs = resources() if args.resources_only else bundle()
    args.output.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    # A repeated generation must never rotate credentials against an existing Postgres directory.
    fd = os.open(args.output, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o644 if args.resources_only else 0o600)
    with os.fdopen(fd, 'w') as output:
        output.write('# Resources only; Secrets must already exist.\n' if args.resources_only else '# PRIVATE: contains credentials. Keep out of Git and retain a secure recovery copy.\n')
        output.write('# Single remote k3s node. Postgres host path: '+STORAGE_PATH+'\n')
        output.write('# Generated by server/k3s/standalone.py; do not hand-edit generated resources.\n')
        yaml.safe_dump_all(docs, output, sort_keys=False, allow_unicode=True)
    print('Created', args.output, '(resources only)' if args.resources_only else '(private complete manifest; credentials not printed)')


if __name__ == '__main__': main()
