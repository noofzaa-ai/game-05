#!/usr/bin/env python3
"""Import the approved v4 hammer preview; keep game's existing dash distance/damage tuning.
Usage: python3 tools/skills/import_hammer_drag.py [preview folder]
No source assets are modified. Motion and camera use preview seconds; recovery blends at3.22.
"""
import json, sys
from pathlib import Path
import numpy as np
from shrink_skills import shrink_motion, shrink_vfx, Glb, scene_import, PAGE_VFX
ROOT=Path(__file__).resolve().parents[2]
src=Path(sys.argv[1]) if len(sys.argv)>1 else ROOT.parent/'art/skills/hammer/ground_drag_preview'
c=json.loads((src/'preview_config.json').read_text())
id=c['id']; folder=ROOT/'art/skills/hammer/ground_drag_ultimate';folder.mkdir(exist_ok=True)
old=json.loads((ROOT/'art/skills/hammer/quake_leap_ultimate/skill.json').read_text())
shrink_motion(str(src/'motion.glb'),str(folder/'motion.glb'))
# Keep the terminal contact pose until the effect ends; gameplay releases/blends at3.22.
g=Glb(str(folder/'motion.glb'))
for a in g.j['animations']:
 for s in a['samplers']:
  t=g.read(s['input']);v=g.read(s['output'])
  s['input']=g.add_accessor(np.concatenate([t,[[c['duration_s']]]]).astype(np.float32),'SCALAR',minmax=True)
  s['output']=g.add_accessor(np.concatenate([v,v[-1:]]).astype(np.float32),{3:'VEC3',4:'VEC4'}[v.shape[1]])
g.save(str(folder/'motion.glb'))
shrink_vfx(str(src/'vfx.glb'),str(folder/'vfx.glb'))
scene_import(str(folder/'vfx.glb'),PAGE_VFX)
# Preserve 240Hz contact sampling rather than lossy compression on the hands.
(folder/'motion.glb.import').write_text('[remap]\nimporter="scene"\nimporter_version=1\ntype="PackedScene"\n[params]\nmeshes/generate_lods=false\nanimation/import=true\nanimation/fps=240\nanimation/remove_immutable_tracks=false\n')
d=dict(old);d.update(id=id,name='อัลติ · ค้อนลากพิภพ',animation=c['animation'],asset_version=4,duration_s=c['duration_s'],timeline=[{'time_s':t,'label':label} for t,label in [(0,'วิ่งลากค้อนมือขวา'),(1.2,'หยุดวิ่ง'),(1.34,'บิดตัวขวาเอื้อมมือซ้าย'),(1.68,'ยกค้อนช้า'),(2.5,'ค้างง้าง'),(2.8,'ฟาด'),(3.04,'กระแทกพื้นระเบิดดิน'),(3.22,'คืนการควบคุม'),(5.32,'เอฟเฟกต์จาง')]])
d['attack']=dict(old['attack']);d['movement']=dict(old['movement']);d['movement'].update(start_time_s=0,end_time_s=1.34)
d['control']={'locomotion_resume_time_s':3.22,'blend_out_s':0.14}
d['flight']={'release_time_s':2.8,'arrival_time_s':3.04}
d['gameplay_events']=[{'time_s':3.04,'name':'earth_ultimate_impact','range_factor':1.0}]
d['vfx_triangles']=9289;d['vfx_triangle_budget']=10000
d['visual']={'vfx_fade_end_time_s':5.32};d.pop('godot_visual',None)
d['camera']={'kind':'hammer_ground_drag','owner_only':True,**c['camera']}
d['impact_anchor']={'time_s':3.04,'marker':'effect_point','floor':'caster_feet'}
d['integration_note']='Approved v4 motion/camera; existing quake dash distance and damage tuning retained, sprint retimed0–1.34; no preview6.35m balance increase. VFX freezes at actual weapon marker on impact. Contact pose blends to locomotion3.22–3.36; authored recovery not added.'
(folder/'skill.json').write_text(json.dumps(d,ensure_ascii=False,indent=2)+'\n')
text=(ROOT/'art/skills/hammer/quake_leap_ultimate/hammer_quake_leap_ultimate.tres').read_text().replace('quake_leap_ultimate','ground_drag_ultimate')
(folder/(id+'.tres')).write_text(text)
p=ROOT/'art/skills/skill_manifest.json';m=json.loads(p.read_text());m['skills']=[x for x in m['skills'] if x['id']!=id];m['skills'].append({'id':id,'name':d['name'],'weapon_type':'hammer','asset_version':4,'resource_path':'res://art/skills/hammer/ground_drag_ultimate/'+id+'.tres','manifest_path':'res://art/skills/hammer/ground_drag_ultimate/skill.json','locomotion_resume_time_s':3.22,'vfx_end_time_s':5.58});m['skills'].sort(key=lambda x:x['id']);m['in_game']['hammer_ultimate']=id;p.write_text(json.dumps(m,ensure_ascii=False,indent=2)+'\n')
(folder/'README.md').write_text('# Hammer ground drag game integration v4\n\n'+d['integration_note']+'\n\nGenerated by tools/skills/import_hammer_drag.py from the approved preview. Rebuild with its source preview folder. Timeline and camera values in skill.json; no source modification.\n')
print('Imported',id)

(folder/"presentation.gd").write_text((src.parents[3]/"scripts/hammer_earth_presentation.gd").read_text().replace("var camera_effects_enabled := true", "var camera_effects_enabled := false"))
